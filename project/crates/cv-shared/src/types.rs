// ---------------------------------------------------------------------------
// Input Events
// ---------------------------------------------------------------------------

/// The source of an input event.
///
/// Distinguishes between human input, AI-generated actions, and system events.
/// This is critical for the priority queue and emergency-stop logic.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
pub enum EventSource {
    /// Input generated by a human operator (highest priority after emergency).
    Human,
    /// Input generated by the AI agent.
    AI,
    /// System-generated events (heartbeat, status updates).
    System,
}

/// Mouse button identifiers.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
pub enum MouseButton {
    /// Left mouse button.
    Left,
    /// Right mouse button.
    Right,
    /// Middle (scroll wheel) mouse button.
    Middle,
}

/// Specific input event types.
///
/// Each variant carries the data needed to replay the event on the remote
/// machine via the platform's input injection API (`SendInput` on Windows).
#[derive(Debug, Clone, PartialEq, Eq, Hash, Serialize, Deserialize)]
pub enum EventType {
    /// Move the mouse cursor to absolute screen coordinates.
    MouseMove {
        /// Absolute X coordinate in screen pixels.
        x: i32,
        /// Absolute Y coordinate in screen pixels.
        y: i32,
    },
    /// Press or release a mouse button.
    MouseClick {
        /// Which button was actuated.
        button: MouseButton,
        /// `true` if the button was pressed, `false` if released.
        down: bool,
    },
    /// Scroll the mouse wheel vertically.
    MouseScroll {
        /// Positive values scroll up, negative values scroll down.
        delta: i32,
    },
    /// Press or release a keyboard key.
    KeyPress {
        /// Virtual-key code (Windows `wVk` format).
        keycode: u16,
        /// `true` if the key was pressed, `false` if released.
        down: bool,
    },
    /// Type a sequence of Unicode characters.
    KeyType {
        /// The text string to type character-by-character.
        text: String,
    },
}

/// Priority levels for input events.
///
/// # Ordering
///
/// Priorities are ordered from highest to lowest urgency:
/// - [`Priority::P0_Emergency`] — Emergency stop (always processed first).
/// - [`Priority::P1_Human`] — Human input (always takes precedence over AI).
/// - [`Priority::P2_AI_Confirmed`] — AI actions that require human confirmation.
/// - [`Priority::P3_AI_Autonomous`] — Fully autonomous AI actions (lowest).
///
/// This ordering is implemented via [`Ord`] so the type can be used directly
/// in a [`std::collections::BinaryHeap`].
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
pub enum Priority {
    /// Emergency stop — immediately halts all AI activity.
    P0_Emergency,
    /// Human input — always takes precedence over AI actions.
    P1_Human,
    /// AI action that has been explicitly confirmed by a human.
    P2_AI_Confirmed,
    /// Fully autonomous AI action (lowest priority).
    P3_AI_Autonomous,
}

impl Priority {
    /// Returns the numeric priority value.
    ///
    /// Lower numbers = higher priority (0 is highest, 3 is lowest).
    pub fn as_u8(&self) -> u8 {
        match self {
            Priority::P0_Emergency => 0,
            Priority::P1_Human => 1,
            Priority::P2_AI_Confirmed => 2,
            Priority::P3_AI_Autonomous => 3,
        }
    }
}

impl Ord for Priority {
    /// Reversed ordering so that P0 (highest) sorts first.
    ///
    /// `BinaryHeap` is a max-heap, so we compare "other vs self" so that
    /// lower numeric values (higher priority) come out first.
    fn cmp(&self, other: &Self) -> std::cmp::Ordering {
        other.as_u8().cmp(&self.as_u8())
    }
}

impl PartialOrd for Priority {
    fn partial_cmp(&self, other: &Self) -> Option<std::cmp::Ordering> {
        Some(self.cmp(other))
    }
}

// ---------------------------------------------------------------------------
// InputEvent
// ---------------------------------------------------------------------------

/// A complete input event as transmitted over the WebRTC DataChannel.
///
/// This struct is serialized to JSON (or protobuf) and sent to the remote
/// peer, where it is deserialized and replayed via the input injection API.
///
/// # Fields
///
/// - `source`: Who/what generated the event.
/// - `event_type`: What kind of input action this is.
/// - `priority`: Urgency level for the priority queue.
/// - `payload`: Additional event data (JSON-serialized).
/// - `timestamp`: Unix timestamp in milliseconds (sender clock).
/// - `sequence`: Monotonically increasing sequence number for ordering.
#[derive(Debug, Clone, PartialEq, Eq, Hash, Serialize, Deserialize)]
pub struct InputEvent {
    /// The source that generated this event.
    pub source: EventSource,
    /// The type of input action.
    pub event_type: EventType,
    /// Priority level for queue ordering.
    pub priority: Priority,
    /// JSON-serialized payload (for extensibility).
    pub payload: EventPayload,
    /// Unix timestamp in milliseconds.
    pub timestamp: u64,
    /// Monotonically increasing sequence number.
    pub sequence: u64,
}

/// Additional payload data for an input event.
///
/// This is a thin newtype around `String` that carries JSON data.
/// Using a dedicated type allows us to add validation or structured
/// accessors in the future without breaking the API.
#[derive(Debug, Clone, PartialEq, Eq, Hash, Serialize, Deserialize)]
pub struct EventPayload(pub String);

impl EventPayload {
    /// Create an empty payload.
    pub fn empty() -> Self {
        EventPayload(String::new())
    }

    /// Create a payload from a JSON-serializable value.
    ///
    /// # Errors
    ///
    /// Returns an error if serialization fails.
    pub fn from_json<T: Serialize>(value: &T) -> Result<Self, serde_json::Error> {
        Ok(EventPayload(serde_json::to_string(value)?))
    }
}

impl Default for EventPayload {
    fn default() -> Self {
        Self::empty()
    }
}

