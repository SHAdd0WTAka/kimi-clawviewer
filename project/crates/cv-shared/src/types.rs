//! Shared types used across all ClawViewer crates.
//!
//! This module defines the core data types for sessions, peers, input events,
//! video configuration, and platform abstraction. All types are designed to be
//! thread-safe (`Send + Sync`) and suitable for async contexts.

use serde::{Deserialize, Serialize};
use zeroize::{Zeroize, ZeroizeOnDrop};

// ---------------------------------------------------------------------------
// Identifier types
// ---------------------------------------------------------------------------

/// Unique identifier for a ClawViewer session.
///
/// A session groups a set of peers together for remote desktop sharing.
/// The identifier is typically a human-readable string.
#[derive(Debug, Clone, PartialEq, Eq, Hash, Serialize, Deserialize)]
pub struct SessionId(pub String);

impl SessionId {
    /// Create a new [`SessionId`] from any string-like value.
    pub fn new<S: Into<String>>(id: S) -> Self {
        SessionId(id.into())
    }
}

impl Default for SessionId {
    fn default() -> Self {
        SessionId(String::new())
    }
}

/// Unique identifier for a peer in the ClawViewer network.
///
/// Each installation of ClawViewer has a stable peer ID derived from its
/// Ed25519 public key.
#[derive(Debug, Clone, PartialEq, Eq, Hash, Serialize, Deserialize)]
pub struct PeerId(pub String);

impl PeerId {
    /// Create a new [`PeerId`] from any string-like value.
    pub fn new<S: Into<String>>(id: S) -> Self {
        PeerId(id.into())
    }
}

impl Default for PeerId {
    fn default() -> Self {
        PeerId(String::new())
    }
}

/// Session password used for peer authentication.
///
/// The password is a short human-friendly word (6 alphanumeric characters)
/// that must be shared out-of-band to join a session.
///
/// # Security
///
/// This struct derives [`ZeroizeOnDrop`] to ensure the password is wiped
/// from memory when the value is dropped, preventing leakage via memory
/// inspection.
#[derive(Debug, Clone, PartialEq, Eq, Hash, Serialize, Deserialize, Zeroize, ZeroizeOnDrop)]
pub struct Password(pub String);

impl Password {
    /// Create a new [`Password`] from any string-like value.
    ///
    /// # Security
    ///
    /// The input string will be zeroized when this [`Password`] is dropped.
    pub fn new<S: Into<String>>(pwd: S) -> Self {
        Password(pwd.into())
    }
}

impl Default for Password {
    fn default() -> Self {
        Password(String::new())
    }
}

